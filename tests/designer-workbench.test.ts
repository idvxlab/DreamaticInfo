import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdtemp, readFile, readdir, stat, writeFile, rm } from "node:fs/promises";
import path from "node:path";
import os from "node:os";
const root = await mkdtemp(path.join(os.tmpdir(), "info-design-workbench-"));
process.env.INFO_CONFIG_DIR = root;
const store = await import("../apps/server/src/store.js");
const { DesignerWorkbench, readDesignProgress } = await import("../apps/server/src/designer-workbench.js");
const { Orchestrator } = await import("../apps/server/src/orchestrator.js");
const { fixtureRunner } = await import("./fixtures/workflow-runner.js");
const { ingest } = await import("../apps/server/src/ingest.js");
const { renderDocument } = await import("../apps/server/src/markdown-protocol.js");
const p = await store.create("Narrative test", "live");
await ingest(p, "reading.csv", await readFile("tests/fixtures/reading.csv"));
await new Orchestrator(fixtureRunner).start(p.id);
const ready = await store.get(p.id), design = (await store.readArtifact(ready, "designer")).data;
ready.state.stages.designer = { status: "running", attempts: 1 }; ready.state.stages.builder = { status: "pending", attempts: 0 };
ready.state.status = "running"; ready.state.current_stage = "designer"; ready.state.completed = ["chatbot", "researcher", "analyst"];
await store.save(ready);
const inputs = await store.upstream(ready, "designer"), work = await DesignerWorkbench.open(ready, inputs);
const revision = (s: string) => /草稿版本：([a-f0-9-]{36})/.exec(s)![1];
const section = (story: any) => renderDocument("designer", { ...design, storyline: [story] }).split("## 故事线\n\n")[1].split(/^## /m)[0].trim();
let current = "";
try {
  await test("narrative-only Markdown saves without formal submission and exposes reasons and facts while visuals remain pending", async () => {
    const narrative = { ...design, components: [] };
    current = revision(await work.saveDraft(renderDocument("designer", narrative, "Keep author notes")));
    const progress = await work.progress();
    assert.equal(progress.phase, "narrative"); assert.equal(progress.design?.storyline.length, 2);
    assert.equal(progress.counts.selected_facts, 3); assert.equal(progress.counts.components, 0);
    assert.ok(progress.issues.length); assert.match(progress.design!.storyline[0].rationale, /总量/);
    assert.equal((await store.detail(ready)).design, undefined);
    assert.equal((await store.upstream(ready, "builder")).design, undefined);
    await assert.rejects(work.submit(undefined, current), /草稿校验/);
  });
  await test("local story repairs, appends and reorder preserve other content; stale versions and extra sections are rejected", async () => {
    const story = { ...design.storyline[0], fact_ids: ["unknown-fact"] };
    current = revision(await work.patchStory(current, story.id, section(story)));
    assert.ok((await work.progress()).issues.some(issue => issue.story === story.id && issue.message.includes("unknown-fact")));
    const before = await work.document("draft", current);
    const fixed = revision(await work.patchStory(current, story.id, section(design.storyline[0])));
    await assert.rejects(work.patchStory(current, story.id, section(story)), /版本已变化/);
    current = fixed;
    const after = await work.document("draft", current);
    assert.equal(after!.split("### 条目 2")[1], before!.split("### 条目 2")[1]);
    assert.match(after!, /Keep author notes/);
    await assert.rejects(work.patchStory(current, story.id, section(story) + "\n\n## 说明\nInjected"));
    const appended = { ...design.storyline[1], id: "story-extra", rationale: "Supplemental test narrative" };
    current = revision(await work.patchStory(current, appended.id, section(appended)));
    assert.equal((await work.progress()).counts.stories, 3);
    await assert.rejects(work.reorderStories(current, [appended.id]), /完整保留/);
    current = revision(await work.reorderStories(current, [appended.id, ...design.storyline.map((s: any) => s.id)]));
    assert.equal((await work.progress()).design?.storyline[0].id, appended.id);
    const edits = await Promise.allSettled([work.patchStory(current, appended.id, section(appended)), work.patchStory(current, appended.id, section(appended))]);
    assert.equal(edits.filter(result => result.status === "fulfilled").length, 1);
    current = (await work.progress()).revision!;
  });
  await test("read-only recovery retains paused drafts, changed intent hides old drafts and changed sources invalidate active workbench", async () => {
    ready.state.status = "interrupted"; ready.state.stages.designer.status = "interrupted"; await store.save(ready);
    const directory = path.join(store.projectDir(p.id), "state/drafts/designer");
    const files = (await readdir(directory, { recursive: true })).sort();
    const before = await Promise.all(files.map(async file => [file, (await stat(path.join(directory, file))).mtimeMs]));
    const recovered = await DesignerWorkbench.open(ready, inputs);
    assert.equal((await recovered.progress()).revision, current);
    assert.match(await recovered.readDraft(), /Supplemental test narrative/);
    await readDesignProgress(ready, inputs);
    assert.deepEqual(await Promise.all(files.map(async file => [file, (await stat(path.join(directory, file))).mtimeMs])), before);
    assert.equal((await (await DesignerWorkbench.open(ready, { ...inputs, intent: { changed: true } })).progress()).status, "stale");
    const source = inputs.research.sources[0], file = path.join(store.projectDir(p.id), source.path), original = await readFile(file);
    await writeFile(file, Buffer.concat([original, Buffer.from("\nChanged source")]));
    await assert.rejects(work.submit(undefined, current), /来源内容已变化/);
    assert.equal((await readDesignProgress(ready, inputs))?.status, "stale");
    await writeFile(file, original);
  });
  await test("component repairs target one item, keep other Markdown, reject wrong tools and stale versions, and append to an empty component list", async () => {
    const componentSection = (component: any) => renderDocument("designer", { ...design, components: [component] }).split("## 组件\n\n")[1].split(/^## /m)[0].trim();
    const target = { ...structuredClone(design.components[1]), title: "Repaired metric", mapping: { ...design.components[1].mapping, unit: "wrong-unit" } };
    current = revision(await work.patchComponent(current, target.id, componentSection(target)));
    assert.equal((await work.progress()).counts.components, 1);
    assert.ok((await work.progress()).issues.some(issue => issue.component === target.id && issue.message.includes("wrong-unit")));
    const before = await work.document("draft", current);
    const selected = await work.readDraft({ component_id: target.id });
    assert.match(selected, /Repaired metric/); assert.ok(!selected.includes("| 编号 | story-intro |"));
    await assert.rejects(work.readDraft({ component_id: target.id, story_id: design.storyline[0].id }), /仅指定/);
    await assert.rejects(work.patchStory(current, target.id, componentSection(target)), /patch_design_component/);
    assert.equal((await work.progress()).revision, current);
    await assert.rejects(work.patchComponent(current, design.storyline[0].id, section(design.storyline[0])), /patch_design_story/);
    target.mapping.unit = design.components[1].mapping.unit;
    const stale = current;
    current = revision(await work.patchComponent(current, target.id, componentSection(target)));
    assert.equal((await work.document("draft", current))!.split("## 组件")[0], before!.split("## 组件")[0]);
    assert.match((await work.document("draft", current))!, /Keep author notes/);
    await assert.rejects(work.patchComponent(stale, target.id, componentSection(target)), /版本已变化/);
    await assert.rejects(work.patchComponent(current, target.id, componentSection(target) + "\n\n## 说明\nInjected"));
  });
  await test("all component diagnostics are located, and mixed series remain blocked even when mapping repeats the mixed unit", async () => {
    const { designReferenceIssues } = await import("../apps/server/src/design-validation.js");
    const { validateReferences } = await import("../apps/server/src/validation.js");
    const { analystIssues } = await import("../apps/server/src/analyst-validation.js");
    const { hasMixedUnits } = await import("../packages/shared/units.js");
    const bad = structuredClone(design); bad.components[1].mapping.unit = "wrong-metric"; bad.components[3].mapping.unit = "wrong-series"; bad.components[0].fact_ids = ["unknown-fact"];
    const issues = designReferenceIssues(bad, inputs.datafacts);
    assert.ok(issues.some(issue => issue.component === bad.components[0].id && issue.message.includes("unknown-fact")));
    assert.ok(issues.some(issue => issue.component === bad.components[1].id && issue.message.includes("wrong-metric") && issue.message.includes("要求")));
    assert.ok(issues.some(issue => issue.component === bad.components[3].id && issue.message.includes("wrong-series")));
    const mixed = structuredClone(inputs.datafacts), fact = mixed.facts.find((item: any) => item.id === "fact-trend");
    fact.specification.series_unit = "人、%";
    const misleading = structuredClone(design); misleading.components[3].mapping.unit = "人、%";
    assert.throws(() => validateReferences("designer", misleading, { datafacts: mixed }), /混合单位/);
    assert.ok(designReferenceIssues(misleading, mixed).some(issue => issue.component === "chart" && issue.fix.includes("metric")));
    assert.ok((await analystIssues(ready, mixed, inputs.research)).some(issue => issue.location.includes("序列单位") && issue.message.includes("混合单位")));
    for (const unit of ["%、OR", "千、%", "kg; %"]) assert.equal(hasMixedUnits(unit), true);
    for (const unit of ["mg/dL", "kg·m⁻²", "%", "千人"]) assert.equal(hasMixedUnits(unit), false);
  });
  await test("component-story mappings and units are checked, final revision alone submits and only commit enables Builder", async () => {
    const bad = structuredClone(design); bad.components[1].story_ids = ["unknown-story"];
    current = revision(await work.saveDraft(renderDocument("designer", bad), current));
    await assert.rejects(work.submit(undefined, current), /未知段落/);
    bad.components[1].story_ids = ["story-evidence"];
    current = revision(await work.saveDraft(renderDocument("designer", bad), current));
    await assert.rejects(work.submit(undefined, current), /组件事实不属于/);
    current = revision(await work.saveDraft(renderDocument("designer", design), current));
    const parsed = await work.submit(undefined, current);
    assert.deepEqual(parsed.data, design); assert.equal((await store.upstream(ready, "builder")).design, undefined);
    await store.commit(ready, "designer", parsed.data, parsed.notes, "fixture-hash", parsed.markdown);
    assert.equal(await readDesignProgress(ready, inputs), undefined);
    assert.deepEqual((await store.upstream(ready, "builder")).design, design);
  });
} finally { await rm(root, { recursive: true, force: true }); }
