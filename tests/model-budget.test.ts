import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm, readFile } from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import Conversation from '../apps/web/src/Conversation.js';
const root = await mkdtemp(path.join(os.tmpdir(), 'info-model-budget-'));
process.env.INFO_CONFIG_DIR = root;
const store = await import('../apps/server/src/store.js');
const { Orchestrator } = await import('../apps/server/src/orchestrator.js');
const { hash } = await import('../apps/server/src/validation.js');
const { saveRuntimeConfig } = await import('../apps/server/src/config-store.js');
try {
  await test('explicit grants serialize, preserve usage and history, and never start generation', async () => {
    const p = await store.create('Model budget fixture', 'live');
    p.state.status = 'failed'; p.state.error = '运行 model 次数预算已耗尽';
    await store.save(p);
    const scope = hash({ brief: p.brief, messages: p.messages.filter(m => m.role === 'user'), uploads: p.uploads.map(u => u.sha256) });
    const file = path.join(store.projectDir(p.id), 'state/run-usage.json');
    const counts = { model: 120, tool: 223, repair: 2, reported_cost_usd: 0.98 };
    await store.atomic(file, JSON.stringify({ scope, counts }));
    let calls = 0;
    const scheduler = new Orchestrator(async (_p, _role, _config, ctx) => { calls++; ctx.consume?.('model'); throw new Error('Must not generate'); });
    assert.throws(() => scheduler.addModelBudget(p.id, 0), /整数/);
    assert.throws(() => scheduler.addModelBudget(p.id, 1.5), /整数/);
    const grant = scheduler.addModelBudget(p.id, 40);
    assert.throws(() => scheduler.addModelBudget(p.id, 40), /暂停/);
    await grant;
    let usage = JSON.parse(await readFile(file, 'utf8'));
    assert.equal(usage.counts.model, 120); assert.equal(usage.counts.model_task_limit, 160);
    assert.equal(usage.counts.repair, 2); assert.equal(usage.counts.reported_cost_usd, 0.98);
    assert.equal(usage.grants.length, 1); assert.equal(usage.grants[0].amount, 40);
    await scheduler.addModelBudget(p.id, 20);
    usage = JSON.parse(await readFile(file, 'utf8'));
    assert.equal(usage.counts.model_extra_limit, 60); assert.equal(usage.grants.length, 2);
    assert.equal(calls, 0);
    assert.equal((await store.get(p.id)).state.status, 'failed');
    await scheduler.start(p.id);
    usage = JSON.parse(await readFile(file, 'utf8'));
    assert.equal(calls, 1); assert.equal(usage.counts.model, 121);
    assert.equal(usage.counts.run_model, 1); assert.equal(usage.grants.length, 2);
    assert.equal(usage.counts.repair, 2); assert.equal(usage.counts.reported_cost_usd, 0.98);
    const stopped = await store.get(p.id);
    stopped.state.status = 'running'; await store.save(stopped);
    await assert.rejects(scheduler.addModelBudget(p.id, 40), /暂停/);
    stopped.state.status = 'failed'; await store.save(stopped);
    p.brief += ' changed'; await store.save(p);
    await assert.rejects(scheduler.addModelBudget(p.id, 40), /范围已变化/);
    await assert.rejects(saveRuntimeConfig({ values: { DREAMATIC_MODEL_RUN_LIMIT: '1.5' } }), /整数/);
    await saveRuntimeConfig({ values: { DREAMATIC_MODEL_RUN_LIMIT: '30', DREAMATIC_MODEL_TASK_LIMIT: '200' } });
  });
  await test('conversation exposes used/limit and an explicit grant without silently continuing', () => {
    const p: any = { id: 'fixture', messages: [], state: { status: 'failed', stages: Object.fromEntries(['chatbot','researcher','analyst','designer','builder'].map(role => [role, {status:'pending',attempts:0}])), current_stage: null, error: '预算已耗尽', execution_budget: { model: 120, tool: 223 } } };
    const html = renderToStaticMarkup(createElement(Conversation, { project: p, events: [], text: '', setText: () => {}, files: [], setFiles: () => {}, disabled: false, pending: false, error: '', clearError: () => {}, onSend: async () => {}, onPause: () => {}, onContinue: () => {}, onAddModelBudget: () => {}, onRerun: () => {}, onPreview: () => {} }));
    assert.match(html, /120 \/ 120/); assert.match(html, /追加 40 次模型额度/); assert.match(html, /追加后点击/);
  });
} finally { await rm(root, { recursive: true, force: true }); }
